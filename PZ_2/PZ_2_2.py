#Вариант 23. Дано целое число, больше 999. Используя одну операцию деления нацело и одну операцию взятия остатка от деления,
# найти цифру, соответсвующую разряду тысяч в записиси этого числа.

try:
    x = int(input("Введите целое число: ")) #Проверяем целое ли число ввел пользователь
    print((x // 1000) % 10) if x > 999 else print("Введите число больше 999")
except:
    print("Вы ввели не целое число!") #Если введено не целое число, сообщае об этом
