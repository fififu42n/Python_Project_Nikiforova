#Дано множество A из N точек (точки заданы своими координатами x, y). Среди всех точек
#этого множества, лежащих во второй четверти, найти точку, наиболее удаленную от начала
#координат. Если таких точек нет, то вывести точку с нулевыми координатами.
#
#Расстояние R между точками с координатами (x1, y1) и (x2, y2) вычисляется по формуле:
#R = Корень из (x2 - x1)^2 + (y2 - y1)^2
#Для хранения данных о каждом наборе точек следует использовать по два списка:
#Первый список для хранения абсцисс, второй - для хранения ординат
import random

def generation_X(n): #генеруем точки X
    list_X = []
    i = 0
    while i < n:
        list_X.append(random.randint(1, 10))
        i += 1
    return list_X

def generation_Y(n): #генерируем точки Y
    list_Y = []
    i = 0
    while i < n:
        list_Y.append(random.randint(1,10))
        i += 1
    return list_Y

def poisk(X, Y, n): #находим максимально удаленные точки
    con = 0 #счетчик условия
    maxX = 0 # начальное координаты (0, 0)
    maxY = 0
    for i in range(n):
        x1 = X[i]
        y1 = Y[i]
        if x1 > maxX and y1 > maxY: #если точка удалена от (0, 0), то она становится максимальной для сравнения
            maxX = x1
            maxY = y1
        else:
            con += 1 #иначе в счетчике прибавляется 1
    if con == n: #если ни одно из условий не прошло
        print("Нет максимально удаленных точек от оси (0, 0)!")
    else:
        print(f"Максимально удаленная точка от середины координат (0, 0): {maxX}, {maxY}")

n = int(input("Введите количество точек, которые хотите проанализировать: "))
X = generation_X(n)
Y = generation_Y(n)
print(f"Список координат точек X: {X}")
print(f"Список координат точек Y: {Y}")
poisk(X, Y, n)






