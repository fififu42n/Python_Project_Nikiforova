#Ввести 4 числа. Найти и вывести на экран количество четных чисел.

con = 0
bob = 0
a = int(input("Введите 1 число: "))
b = int(input("Введите 2 число: "))
c = int(input("Введите 3 число: "))
d = int(input("Введите 4 число: "))

for i in [a,b,c,d]:
    if i % 2 == 0:
        con += 1
    if i % 2 != 0:
        bob += 1

if bob == 4:
    print("В ряду нет четных чисел")
else:
    print("Количество четных чисел: ", con)