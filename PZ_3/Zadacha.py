#Нужно определить простое число или не простое, делится на саму
#себя или на единицу

def tcet(x):
    for i in range(2, int(x**0.5) + 1):
        if x%i == 0:
            return False
    return True

x = int(input("Введите число: "))
if x <= 1:
    print("Число не простое, и не сложное, т.к. оно меньше, или равно 1")
elif tcet(x):
    print("Это простое число")
else:
    print("Это составное число")


