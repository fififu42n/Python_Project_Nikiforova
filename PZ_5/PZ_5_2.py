#Описать функцию Mean(X, Y, AMean, GMean), вычисляющую среднее арифметическое AMean = (X+Y)/2 и среднее
#геометрическое GMean = y/X Y двух положительных чисел X и Y (X и Y - входные, AMean и GMean - выходные параметры вещественного типа).
#С помощью этой функции найти среднее арифметическое и среднеегеометрическое для пар (A, B),(A, C), (A, D),
#если даны A, B, C, D

def Mean(X,Y):
    AMean = (X + Y)/2
    GMean = Y/X
    return(f"{AMean}, {GMean}")

A = int(input("Введите число A: "))
B = int(input("Введите число B: "))
C = int(input("Введите число C: "))
D = int(input("Введите число D: "))

while A < 0 or B < 0 or C < 0 or D < 0:
    print("Вы ввели неккоректные данные, числа должны быть положительны!")
    A = int(input("Введите число A: "))
    B = int(input("Введите число B: "))
    C = int(input("Введите число C: "))
    D = int(input("Введите число D: "))

print(f"Вычисление среднего арифметического и среднего геометрического для (A, B): {Mean(A,B)}")
