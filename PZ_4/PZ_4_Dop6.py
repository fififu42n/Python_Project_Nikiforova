#Ввести N чисел. Посчитать и вывести количество чисел равных нулю

con = 0
num_list = []
n = int(input("Выберите количество чисел которые хотите ввести: "))
for a in range(n):
    b = int(input("Введите число: "))
    num_list.append(b)
    if b == 0:
        con += 1

if con > 0:
    print(f"Количество нулей в ряду {num_list} равно: {con}")
else:
    print("В введенных числах нет нулей")