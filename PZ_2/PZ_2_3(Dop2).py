#Ввести число. Если оно четное, разделить его на 4, если нечетное - умножить на 5.

a = input("Введите число: ")
while type(a) != int :
        try:
            a = int(a)
        except ValueError:
            print("Вы ввели неправильные данные:")
            a = input("Введите число: ")
if a%2==0:
    print("Число четное, делим его на 4: ", a/4)
else:
    print("Число не четное, умножаем его на 5: ", a*5)