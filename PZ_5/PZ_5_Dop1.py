#Даны три целых числа.Определить у какого числа больше сумма цифр. Вывод результата предусмотрен в
#основной программе.Расчет суммы цифр оформлять в функции.

def fif(x):
    con = 0
    while x > 10:
        i = x % 10
        x = x//10
        con += i
    a = con + x
    return a

a = int(input("Введите первое число: "))
b = int(input("Введите второе число: "))
c = int(input("Введите третье число: "))
a1 = fif(a)
b1 = fif(b)
c1 = fif(c)
print(f"Сумма цифр в числе {a} = {fif(a)}")
print(f"Сумма цифр в числе {b} = {fif(b)}")
print(f"Сумма цифр в числе {c} = {fif(c)}")
print(f"Максимальная сумма цифр в числе среди всех: {max(a1, b1, c1)}")