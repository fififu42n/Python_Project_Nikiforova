#Дано целое число. Если оно является положительным, то прибавить к нему 20,
#в противном случае вычесть из него 5

x = input("Введите число: ")
while type(x) != int:
    try:
        x = int(x)
    except ValueError:
        print("Вы ввели не число!")
        x = input("Введите число: ")

if x>0:
    print("Число положительное, прибавляем к нему 20: ", x+20)
else:
    print("Число отрицательное, вычитаем из него 5: ", x-5)