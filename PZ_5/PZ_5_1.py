#Найти сумму чисел ряда 1,2,3,... 60 с использованием функции нахождения суммы.
# Использовать локальные переменные

def summa():
    start = 1
    end = 60
    con = 0
    for i in range(start, end + 1):
        con += i
    return con

print(f"Сумма чисел от 1 до 60: {summa()}")