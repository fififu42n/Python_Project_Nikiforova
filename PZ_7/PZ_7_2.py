#Дана строка,состоящая из русских слов, разделенных пробелами (одним или несколькими)
#Найти длину самого длинного слова.
max = 0
a = input("Введите пару русских слов: ")
list = a.split()

for i in list:
    m = len(i)
    if m > max:
        max = m

print(f"Количество символов в самом длинному слове: {max}")