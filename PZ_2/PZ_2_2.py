#Вариант 23. Дано целое число, больше 999. Используя одну операцию деления нацело и одну операцию взятия остатка от деления, найти цифру, соответсвующую разряду тысяч в записиси этого числа.

x = int(input("Введите число: ")) #Ввожим число, с которым будем работать
y = (x/10)%10 #Сначачала делаем целое деление /, потом остаточное %, в результате находим раздел сотен
print(int(y)) #Выводим число Y в формате целого числа